using System.Text.Json;
using System.Text.Json.Serialization;
using Binance.Common;

namespace Binance.DerivativesTradingUsdsFutures.RestApi;

public sealed class GetFundingRateHistoryResponseInner
{
    /// <summary>Symbol.</summary>
    [JsonPropertyName("symbol")]
    public string? Symbol { get; set; }

    /// <summary>Funding Rate.</summary>
    [JsonPropertyName("fundingRate")]
    public string? FundingRate { get; set; }

    /// <summary>Funding Time.</summary>
    [JsonPropertyName("fundingTime")]
    public long? FundingTime { get; set; }

    /// <summary>mark price associated with a particular funding fee charge</summary>
    [JsonPropertyName("markPrice")]
    public string? MarkPrice { get; set; }

    /// <summary>
    /// Funding rate type. Regular for the normal funding rate; Special for the additional funding rate
    /// generated by stock dividends.
    /// </summary>
    [JsonPropertyName("rateType")]
    public string? RateType { get; set; }
}
