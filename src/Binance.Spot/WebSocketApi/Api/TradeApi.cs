    /// <summary>See Trailing Stop order FAQ</summary>
    public decimal? TrailingDelta { get; init; }

    /// <summary>
    /// Used with LIMIT, STOP_LOSS_LIMIT, and TAKE_PROFIT_LIMIT to create an iceberg order.
    /// </summary>
    public decimal? IcebergQty { get; init; }

    public long? StrategyId { get; init; }

    /// <summary>The value cannot be less than 1000000.</summary>
    public long? StrategyType { get; init; }

