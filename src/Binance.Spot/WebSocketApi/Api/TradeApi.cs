    /// <remarks>
    /// <para>
    /// If both cancelOrderId and cancelOrigClientOrderId parameters are provided, the cancelOrderId is
    /// searched first, then the cancelOrigClientOrderId from that result is checked against that order.
    /// </para>
    /// <para>If both conditions are not met the request will be rejected.</para>
    /// </remarks>
    public long? CancelOrderId { get; init; }

    /// <summary>Either cancelOrderId or cancelOrigClientOrderId must be sent.</summary>
    /// <remarks>
    /// <para>
    /// If both cancelOrderId and cancelOrigClientOrderId parameters are provided, the cancelOrderId is
    /// searched first, then the cancelOrigClientOrderId from that result is checked against that order.
    /// </para>
    /// <para>If both conditions are not met the request will be rejected.</para>
    /// </remarks>
    public string? CancelOrigClientOrderId { get; init; }

    /// <summary>Used to uniquely identify this cancel. Automatically generated by default.</summary>
    public string? CancelNewClientOrderId { get; init; }

    public OrderCancelReplaceTimeInForce? TimeInForce { get; init; }

    public decimal? Price { get; init; }

    public decimal? Quantity { get; init; }

    public decimal? QuoteOrderQty { get; init; }

    /// <summary>Used to identify the new order.</summary>
    public string? NewClientOrderId { get; init; }

    /// <summary>
    /// Allowed values: ACK, RESULT, FULL MARKET and LIMIT orders types default to FULL; all other orders
    /// default to ACK
    /// </summary>
